""" 드래곤 커브 / 20260920 / 체감 난이도: G4
소요 시간 17분 / 시도 1회 / 실행 시간 67ms (코드트리) / 메모리 18MB (코드트리)

그냥 최대 차수 커브 하나 만들어놓고 방향 돌려가면서 커브 그렸다.
예전처럼 미리 다 구해놓고 하는거보다는 느리다.
"""


def get_lookup(degree):
    lst = [0]
    for i in range(degree):
        for j in range(len(lst)-1, -1, -1):
            lst.append((lst[j]+1) % 4)
    return lst


if __name__ == '__main__':
    N = int(input())
    board = [[0]*101 for _ in range(101)]
    directions = [(0, 1), (-1, 0), (0, -1), (1, 0)]

    curves = []
    max_degree = 0
    for _ in range(N):
        x, y, d, g = map(int, input().split())
        curves.append([x, y, d, g])
        if g > max_degree:
            max_degree = g

    lookup = get_lookup(max_degree)
    for x, y, d, g in curves:
        board[x][y] = 1
        for i in range(2**g):
            dx, dy = directions[(lookup[i]+d) % 4]
            x, y = x + dx, y + dy
            board[x][y] = 1

    answer = 0
    for r in range(100):
        for c in range(100):
            check = sum([
                board[r][c],
                board[r + 1][c],
                board[r][c + 1],
                board[r + 1][c + 1]
            ])
            if check == 4:
                answer += 1
    print(answer)


