def calc_curve(start, max_step):
    # 메모이제이션 기법을 활용해 드래곤 커브 이동방향을 빠르게 찾자.
    for i in range(max_step):
        # n차 드래곤 커브는 n-1 커브의 이동 히스토리를 그대로 이어 받는다.
        temp = dp[start][i].copy()
        dp[start].append(temp)
        # n차에서 새롭게 추가되는 부분은 n-1차를 역으로 순회하며
        # 각 방향 벡터를 반시계방향으로 90도 회전시킨 것과 동일하다!
        for j in dp[start][i][::-1]:
            dp[start][i+1].append((j+1) % 4)


if __name__ == '__main__':
    # 드래곤 커브 개수
    N = int(input())
    # 커브 정보 저장용 리스트
    curves = []
    # 중복 방지를 위한 카운터 (인덱스: 시작 방향, 값: 최대 차수)
    counter = [0, 0, 0, 0]
    for _ in range(N):
        # 시작 x, 시작 y, 시작 방향, 차수
        x, y, d, g = map(int, input().split())
        # 카운터 업데이트
        counter[d] = max(counter[d], g)
        # 커브 정보 저장
        curves.append([x, y, d, g])

    # 디렉터 벡터 리스트, 동, 북, 서, 남
    directions = [(0, 1), (-1, 0), (0, -1), (1, 0)]
    # 시작 방향, 차수에 따라서 드래곤 커브는 항상 같은 움직임을 가진다.
    # dp[i]: 시작 방향 인덱스가 i인 드래곤 커브 모두 저장
    # dp[i][j]: 시작 방향 인덱스가 i이고, 차수가 j인 드래곤 커브의 이동 방향 히스토리 보관
    dp = [[[0]], [[1]], [[2]], [[3]]]

    # 카운터를 순회하며, dp 배열에 딱 필요한 만큼만 값을 채워넣는다.
    for i in range(4):
        if counter[i] == 0:
            continue
        calc_curve(start=i, max_step=counter[i])

    # x, y는 0이상 100이하, 따라서 101*101 배열 초기화
    arr = [[0] * 101 for _ in range(101)]
    # 커브 이동방향에 맞춰서 배열 채워넣기
    for x, y, d, g in curves:
        arr[x][y] = 1
        for j in dp[d][g]:
            x += directions[j][0]
            y += directions[j][1]
            arr[x][y] = 1

    # 단위 사각형은 선 연결 유무와 상관이 없다.
    unit_count = 0
    # 단위 사각형 개수 세기
    for r in range(100):
        for c in range(100):
            sm = arr[r][c] + arr[r+1][c] + arr[r][c+1] + arr[r+1][c+1]
            if sm == 4:
                unit_count += 1
    # 정답 출력
    print(unit_count)
